'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const files=['capacitor.config.json','tools/build_mobile_web.cjs','.github/workflows/native-apps.yml',
  'remaster/book.js'];
for(const file of files)assert.ok(fs.existsSync(file),file);
const config=JSON.parse(fs.readFileSync('capacitor.config.json','utf8'));
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const html=fs.readFileSync('index.html','utf8');
const worker=fs.readFileSync('sw.js','utf8');
const game=fs.readFileSync('game.js','utf8');
const workflow=fs.readFileSync('.github/workflows/native-apps.yml','utf8');
const book=fs.readFileSync('remaster/book.js','utf8');
assert.match(config.appId,/^[a-z][a-z0-9]*(\.[a-z][a-z0-9]*){2,}$/i);
assert.equal(config.webDir,'public');
assert.ok(!config.server?.url,'native build must bundle assets locally, not serve the GitHub Pages website');
assert.match(pkg.dependencies['@capacitor/android'],/8/);
assert.match(pkg.dependencies['@capacitor/ios'],/8/);
assert.match(pkg.devDependencies['@capacitor/cli'],/8/);
assert.match(workflow,/android-36/);
assert.match(workflow,/assembleDebug/);
assert.match(workflow,/upload-artifact@v4/);
assert.match(workflow,/cap add ios/);
assert.match(workflow,/macos-26/);
assert.match(html,/window\.Capacitor\?\.isNativePlatform\?\.\(\)/);
assert.match(html,/remaster\/book\.js\?v=10/);
assert.match(worker,/remaster\/book\.js\?v=10/);
assert.match(game,/drawTitleBook\?\.\(ctx\)/);
assert.match(game,/drawChapterBook\?\.\(ctx\)/);
assert.match(book,/api\.drawTitleBook=drawTitleBook/);
assert.match(book,/api\.drawChapterBook=drawChapterBook/);
assert.match(fs.readFileSync('remaster/remaster.js','utf8'),/renderingScale\(cssW,cssH\)/);
console.log('Native packaging audit: offline Capacitor Android/iOS; vector book and adaptive canvas budget OK');
