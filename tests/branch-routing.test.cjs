'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=(p)=>fs.readFileSync(p,'utf8');
const pages=read('.github/workflows/pages.yml');
const native=read('.github/workflows/native-apps.yml');
const quality=read('.github/workflows/quality.yml');
assert.match(pages,/on:\s*\n\s*push:\s*\n\s*branches: \[main\]\s*\n\s*workflow_dispatch:/);
assert.match(pages,/validar:\s*\n\s*if: github\.ref == 'refs\/heads\/main' \|\| github\.ref == 'refs\/heads\/web'/);
assert.match(pages,/github\.ref_name == 'main' && 'github-pages' \|\| 'bounce-tales-web'/);
assert.match(native,/branches: \[android, ios\]/);
assert.match(native,/android:\s*\n\s*if: github\.ref == 'refs\/heads\/android'/);
assert.match(native,/ios:\s*\n\s*if: github\.ref == 'refs\/heads\/ios'/);
assert.match(native,/docs\/BRANCH_TARGET\.md/);
assert.match(quality,/branches: \[main, web, android, ios\]/);
const branching=read('docs/BRANCHING.md');
assert.match(branching,/Solo la rama \*\*main\*\* activa automáticamente GitHub Pages/);
assert.match(branching,/No publica Pages ni compila/);
console.log('Branch routing: Pages on main pushes or manual web runs. Android and iOS builds run on their own branches.');
