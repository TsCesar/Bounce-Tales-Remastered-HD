/* Integration checks for the original-art presentation layer. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const read = file => fs.readFileSync(file, 'utf8');
const page = read('index.html');
const game = read('game.js');
const renderer = read('remaster/remaster.js');
const textures = read('remaster/texture-hd.js');
const stylesheet = read('remaster/remaster.css');
const sw = read('sw.js');
const workflow = read('.github/workflows/pages.yml');

assert.match(page, /canvas id="game" width="240" height="320"/);
assert.match(renderer, /const QUALITY = \['classic', 'hd', 'ultra'\]/);
const renderScripts = [...page.matchAll(/<script src="(remaster\/[^"]+)"/g)].map(match => match[1]);
assert.deepEqual(renderScripts, ['remaster/remaster.js?v=14', 'remaster/texture-hd.js?v=9']);
const artShell = [...sw.matchAll(/"(remaster\/[^"]+\.js\?v=\d+)"/g)].map(match => match[1]);
assert.deepEqual(artShell, renderScripts, 'Offline shell must load the same renderers');
assert.ok(page.includes('game.js?v=63') && sw.includes('game.js?v=63'));
const hooks = [...game.matchAll(/BounceRemaster\?\.([A-Za-z]+)/g)].map(match => match[1]);
assert.deepEqual([...new Set(hooks)].sort(), ['beginFrame', 'drawSprite', 'quality']);
assert.match(game, /drawImageMap\(map.frames\[at\],x,y,seen,frame,targetCtx\)/);
assert.match(game, /drawBounceForm\(p\.x,p\.y,r\)[\s\S]*drawBumpyForm\(p\.x,p\.y\)[\s\S]*drawWollyForm\(p\.x,p\.y,r\)/);
assert.match(game, /drawImageMap\(t.imageId,p.x,p.y,new Set\(\),t.active\?t.animFrame:0\)/);
assert.match(game, /particles.draw\(ctx,screenPoint,SCALE,\(id,x,y,frame\)=>drawImageMap\(id,x,y,new Set\(\),frame,ctx\)\)/);
assert.match(game, /if\(mode===S\.play\)\{\s*if\(activeStoryMessage\)drawOriginalStoryMessage\(\)/);
assert.match(game, /rockBreakRuntime\?\.update\(\{/);
assert.match(game, /rockBreakRuntime\?\.reset\(\)/);
assert.match(page, /src\/rock-break\.js\?v=6/);
assert.match(sw, /src\/rock-break\.js\?v=6/);
assert.match(renderer, /ctx\.imageSmoothingEnabled = false/);
assert.match(renderer, /const budget=coarse\?1300000:3200000/);
assert.match(textures, /manifest\.json\?v=9/);
assert.match(textures, /sprite\.sampling==='smooth'/);
assert.match(stylesheet, /top:max\(7px,env\(safe-area-inset-top\)\)/);
assert.match(stylesheet, /#app \.topbar button,#app \.topbar a \{pointer-events:auto;\}/);
assert.match(stylesheet, /pointer:coarse/);
assert.match(stylesheet, /game-controls \{display:none !important;/);
assert.match(workflow, /tools\/build_hd_textures\.py --output public\/remaster\/assets\/hd --scale 4/);
assert.match(workflow, /tools\/validate_hd_textures\.py --output public\/remaster\/assets\/mobile --scale 2/);
console.log('Original-art integration: one scene and animation path, three display modes and matching offline assets.');
