/* Static integration checks for the independent presentation layer. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const files = ['index.html','game.js','remaster/remaster.js','remaster/texture-hd.js','remaster/scenery.js','remaster/materials.js','remaster/book.js','remaster/remaster.css','tools/build_hd_textures.py','tools/validate_hd_textures.py','tools/build_hd_scenery.py','sw.js','.github/workflows/pages.yml'];
for (const name of files) assert.ok(fs.existsSync(name),'Missing '+name);
const page = fs.readFileSync('index.html','utf8');
const game = fs.readFileSync('game.js','utf8');
const renderer = fs.readFileSync('remaster/remaster.js','utf8');
const stylesheet = fs.readFileSync('remaster/remaster.css','utf8');
const sw = fs.readFileSync('sw.js','utf8');
const workflow = fs.readFileSync('.github/workflows/pages.yml','utf8');
assert.match(page,/canvas id="game" width="240" height="320"/,'Logical canvas must remain 240x320');
assert.match(page,/remaster\/remaster\.js\?v=7/);
assert.match(page,/remaster\/book\.js\?v=10/);
assert.match(game,/BounceRemaster\?\.drawTitleBook\?\.\(ctx\)/);
assert.match(game,/BounceRemaster\?\.drawChapterBook\?\.\(ctx\)/);
assert.match(game,/BounceRemaster\?\.drawSelectionArrows\?\.\(ctx,left,right,centerY\)/);
assert.match(fs.readFileSync('remaster/book.js','utf8'),/api.drawSelectionArrows=drawSelectionArrows/);
assert.match(page,/remaster\/remaster\.css\?v=11/);
assert.match(stylesheet,/top:max\(7px,env\(safe-area-inset-top\)\)/);
assert.match(stylesheet,/left:50%;transform:translateX\(-50%\)/);
assert.match(stylesheet,/pointer-events:none/);
assert.match(stylesheet,/#app \.topbar button,#app \.topbar a \{pointer-events:auto;\}/);
assert.match(page,/remaster\/texture-hd\.js\?v=8/);
assert.match(page,/remaster\/scenery\.js\?v=8/);
assert.match(page,/remaster\/materials\.js\?v=4/);
assert.match(game,/BounceRemaster\?\.drawSprite\?\.\(id,x,y,targetCtx\)/);
assert.match(game,/BounceRemaster\?\.drawScenery\?\.\(/);
assert.match(game,/BounceRemaster\?\.drawWaterSurface\?\.\(/);
assert.match(game,/rockBreakRuntime\?\.update\(\{/);
assert.match(game,/rockBreakRuntime\?\.reset\(\)/);
assert.match(page,/src\/rock-break\.js\?v=6/);
assert.match(sw,/src\/rock-break\.js\?v=6/);
assert.match(fs.readFileSync('remaster/texture-hd.js','utf8'),/next\.spriteCount!==326/);
assert.match(fs.readFileSync('remaster/texture-hd.js','utf8'),/next.scale!==expectedScale/);
assert.match(fs.readFileSync('remaster/scenery.js','utf8'),/remaster.drawScenery = drawScenery/);
assert.match(fs.readFileSync('remaster/materials.js','utf8'),/remaster.drawTerrain = drawTerrain/);
assert.match(renderer,/ctx\.imageSmoothingEnabled = false/);
assert.match(renderer,/const budget=coarse\?1300000:3200000/);
assert.match(renderer,/p\.form !== 0/,'Bumpy and Wolly must retain their source form graphics');
assert.doesNotMatch(renderer,/scale = quality === 'ultra' \? 1 : 0\.72/);
assert.match(fs.readFileSync('remaster/texture-hd.js','utf8'),/sprite.sampling==='smooth'/);
assert.doesNotMatch(fs.readFileSync('remaster/materials.js','utf8'),/fractal\(|createPattern\(/);
assert.doesNotMatch(fs.readFileSync('tools/build_hd_textures.py','utf8'),/UnsharpMask|random\.default_rng/);
for(const method of ['beginFrame','drawBounce','drawEgg','drawTerrain','finishScene']){
  assert.ok(game.includes('BounceRemaster?.'+method+'?.('),'Missing '+method+' hook');
  assert.ok(renderer.includes('api.'+method+' = '),'Missing implementation for '+method);
}
assert.match(renderer,/const WORLD_W = 240, WORLD_H = 320/);
assert.match(stylesheet,/pointer:coarse/);
assert.match(stylesheet,/game-controls \{display:none !important;/);
assert.match(sw,/bounce-tales-v62/);
assert.match(sw,/remaster\/remaster\.js\?v=7/);
assert.match(sw,/remaster\/book\.js\?v=10/);
assert.doesNotMatch(sw,/"remaster\/assets\/hd\/manifest\.json\?v=2"/);
assert.match(fs.readFileSync('remaster/texture-hd.js','utf8'),/manifest\.json\?v=8/);
assert.match(workflow,/tools\/build_hd_textures\.py/);
assert.match(workflow,/tools\/build_hd_scenery\.py/);
assert.match(workflow,/assets\/mobile --scale 2/);
assert.match(fs.readFileSync('remaster/scenery.js','utf8'),/MAX_CACHED_BACKDROPS/);
assert.match(workflow,/cp -a src assets remaster public\//);
assert.equal((page.match(/remaster\/remaster\.js/g)||[]).length,1);
console.log('Remaster integration: 240x320 simulation, 5 visual hooks, static assets and Pages deployment OK');
